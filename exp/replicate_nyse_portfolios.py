def main() -> None:
    print("=" * 65)
    print("Experiment 4 – NYSE Diversity Portfolios (Synthetic Data)")
    print("=" * 65)
    print()
    print("DISCLAIMER: CRSP data is NOT available. This experiment uses a")
    print("synthetic market calibrated to NYSE 2002-2021 characteristics.")
    print("Results illustrate structural SPT properties, not historical data.")
    print()

    # ------------------------------------------------------------------
    # 1. Regenerate synthetic NYSE data (same seed as Exp 3)
    # ------------------------------------------------------------------
    print("[1/6] Generating synthetic NYSE market…")
    P, N, m, trading_dates = generate_synthetic_nyse(
        n_stocks=600, n_trading_days=5036, seed=42,
        split_prob_annual=0.08, reverse_split_prob_annual=0.02,
        sigma_cross=0.20, mu_annual=0.08, start_date="2002-01-02",
        price_range=(5.0, 500.0), cap_range=(1e8, 1e12),
    )
    S = P * N

    # ------------------------------------------------------------------
    # 2. Rebuild quarterly universes and benchmarks
    # ------------------------------------------------------------------
    print("[2/6] Rebuilding quarterly universes and benchmarks…")
    universes_P, universes_S = build_quarterly_universes(P, S, trading_dates, n=500)

    # Four benchmarks (same as Exp 3)
    I_mu_P = build_cap_weighted_benchmark(P, N, m, universes_P, trading_dates)
    I_mu_S = build_cap_weighted_benchmark(P, N, m, universes_S, trading_dates)
    I_nu_P, _ = build_price_weighted_benchmark(P, N, m, universes_P, trading_dates)
    I_nu_S, _ = build_price_weighted_benchmark(P, N, m, universes_S, trading_dates)

    # Log benchmarks and weighting effects for rebasing
    L_mu_P = np.log(I_mu_P)
    L_mu_S = np.log(I_mu_S)
    L_nu_P = np.log(I_nu_P)
    L_nu_S = np.log(I_nu_S)
    W_P = L_nu_P - L_mu_P   # Weighting effect: price-univ price-wtd vs cap-wtd
    W_S = L_nu_S - L_mu_S   # Weighting effect: cap-univ price-wtd vs cap-wtd

    # Split and rebalance dates (for J_p)
    rebal_dates_P = _get_rebal_dates(universes_P)
    rebal_dates_S = _get_rebal_dates(universes_S)
    print("    Computing split dates for each universe (may take a moment)…")
    split_dates_P = _get_split_dates(m, universes_P, trading_dates)
    split_dates_S = _get_split_dates(m, universes_S, trading_dates)
    print(f"    Split dates in U^P: {len(split_dates_P)},  U^S: {len(split_dates_S)}")

    # ------------------------------------------------------------------
    # 3. Pre-build weight matrices for all four (basis, universe) combos
    # ------------------------------------------------------------------
    print("[3/6] Building benchmark weight matrices (4 combinations)…")
    weight_matrices = {}
    for basis, universes, univ_label in [
        ("price", universes_P, "P"),
        ("price", universes_S, "S"),
        ("cap",   universes_P, "P"),
        ("cap",   universes_S, "S"),
    ]:
        key = (basis, univ_label)
        print(f"    Building ({basis}, U^{univ_label})…")
        w_end, w_adj = _build_weight_matrices(P, N, m, universes, trading_dates, basis)
        weight_matrices[key] = (w_end.values, w_adj.values, w_end.columns.tolist())

    # ------------------------------------------------------------------
    # 4. Run diversity portfolios and compute decomposition
    # ------------------------------------------------------------------
    print("[4/6] Running diversity portfolios and computing decompositions…")
    results = {}   # key: (p, basis, univ_label) -> dict of results

    benchmark_map = {
        ("price", "P"): (I_nu_P, L_nu_P),
        ("price", "S"): (I_nu_S, L_nu_S),
        ("cap",   "P"): (I_mu_P, L_mu_P),
        ("cap",   "S"): (I_mu_S, L_mu_S),
    }
    split_dates_map = {
        "P": split_dates_P,
        "S": split_dates_S,
    }
    rebal_dates_map = {
        "P": rebal_dates_P,
        "S": rebal_dates_S,
    }
    universes_map = {
        "P": universes_P,
        "S": universes_S,
    }

    for p in P_VALUES:
        for basis in ("price", "cap"):
            for univ_label in ("P", "S"):
                key = (p, basis, univ_label)
                print(f"    p={p}  basis={basis}  U^{univ_label}…")

                # Run portfolio
                universes = universes_map[univ_label]
                wealth, _ = run_diversity_portfolio(
                    P, N, m, universes, trading_dates, p=p, basis=basis, V0=1.0,
                )

                # Own benchmark
                I_bench, L_bench = benchmark_map[(basis, univ_label)]
                log_rel_wealth = np.log(wealth) - L_bench

                # Decomposition
                w_end_arr, w_adj_arr, all_tickers = weight_matrices[(basis, univ_label)]
                C_p, E_p = _compute_decomposition(w_end_arr, w_adj_arr, p, trading_dates)

                # J_p only for price basis (cap weights are split-invariant)
                if basis == "price":
                    J_p = _compute_Jp(
                        w_adj_arr, w_end_arr,
                        split_dates=split_dates_map[univ_label],
                        rebal_dates=rebal_dates_map[univ_label],
                        p=p,
                        trading_dates=trading_dates,
                        all_tickers=all_tickers,
                    )
                else:
                    J_p = pd.Series(0.0, index=trading_dates, name="J_p")

                C_plus_E = C_p + E_p
                residual = log_rel_wealth - (C_p + E_p + J_p)

                results[key] = {
                    "wealth": wealth,
                    "log_rel_wealth": log_rel_wealth,
                    "C_p": C_p,
                    "E_p": E_p,
                    "J_p": J_p,
                    "C_plus_E": C_plus_E,
                    "residual": residual,
                }

    # ------------------------------------------------------------------
    # 5. Save CSV results
    # ------------------------------------------------------------------
    print("[5/6] Saving CSV results…")

    # Terminal values table
    rows = []
    for (p, basis, univ_label), res in results.items():
        bench_term = np.exp(benchmark_map[(basis, univ_label)][1].iloc[-1])
        row = {
            "p": p,
            "basis": basis,
            "universe": univ_label,
            "wealth_T": res["wealth"].iloc[-1],
            "log_rel_T": res["log_rel_wealth"].iloc[-1],
            "C_p_T": res["C_p"].iloc[-1],
            "E_p_T": res["E_p"].iloc[-1],
            "J_p_T": res["J_p"].iloc[-1],
            "CplusE_T": res["C_plus_E"].iloc[-1],
            "residual_T": res["residual"].iloc[-1],
        }
        # Rebased to cap-weighted benchmark
        if basis == "price":
            W_rebase = W_P if univ_label == "P" else W_S
            row["log_rel_rebased_T"] = res["log_rel_wealth"].iloc[-1] + W_rebase.iloc[-1]
        else:
            row["log_rel_rebased_T"] = res["log_rel_wealth"].iloc[-1]
        rows.append(row)

    terminal_df = pd.DataFrame(rows).set_index(["p", "basis", "universe"])
    terminal_df.to_csv(RESULTS_DIR / "exp4_terminal_values.csv")

    # Time-series results for each combination
    for (p, basis, univ_label), res in results.items():
        fname = f"exp4_ts_p{str(p).replace('.','')}_basis{basis}_univ{univ_label}.csv"
        ts_df = pd.DataFrame({
            "wealth": res["wealth"],
            "log_rel_wealth": res["log_rel_wealth"],
            "C_p": res["C_p"],
            "E_p": res["E_p"],
            "J_p": res["J_p"],
            "C_plus_E": res["C_plus_E"],
            "residual": res["residual"],
        })
        ts_df.to_csv(RESULTS_DIR / fname)

    # ------------------------------------------------------------------
    # 6. Plots
    # ------------------------------------------------------------------
    print("[6/6] Generating plots…")

    years_idx = pd.DatetimeIndex(trading_dates)
    year_ticks = trading_dates[
        pd.Series(years_idx.year, index=trading_dates)
        .ne(pd.Series(years_idx.year, index=trading_dates).shift())
        .values
    ]

    def _set_year_ticks(ax):
        ax.set_xticks(year_ticks[::2])
        ax.set_xticklabels(
            [str(d.year) for d in year_ticks[::2]], rotation=45, ha="right", fontsize=8
        )

    # ---- Figure 1: Relative wealth for all p – own benchmark ------------
    fig, axes = plt.subplots(2, 2, figsize=(14, 10), sharex=True)
    fig.suptitle(
        "Diversity Portfolio Log Relative Wealth vs Own Benchmark (Synthetic Data)\n"
        "[DISCLAIMER: synthetic data — not actual CRSP/NYSE data]",
        fontsize=11,
    )
    panel_configs = [
        (axes[0, 0], "price", "P", r"Price-wtd / Price-univ $U^P$ → $I_\nu^P$"),
        (axes[0, 1], "price", "S", r"Price-wtd / Cap-univ $U^S$ → $I_\nu^S$"),
        (axes[1, 0], "cap",   "P", r"Cap-wtd / Price-univ $U^P$ → $I_\mu^P$"),
        (axes[1, 1], "cap",   "S", r"Cap-wtd / Cap-univ $U^S$ → $I_\mu^S$"),
    ]
    for ax, basis, univ_label, title in panel_configs:
        for p_val, col in zip(P_VALUES, COLORS_P):
            key = (p_val, basis, univ_label)
            res = results[key]
            ax.plot(
                trading_dates,
                res["log_rel_wealth"].values,
                lw=1.1, color=col,
                label=f"$p = {p_val}$",
            )
        ax.axhline(0, color="black", lw=0.6, ls="--")
        ax.set_title(title, fontsize=9)
        ax.set_ylabel("log(V/I)")
        ax.legend(fontsize=7, ncol=2)
        _set_year_ticks(ax)

    plt.tight_layout()
    fig.savefig(RESULTS_DIR / "exp4_relative_wealth.png", bbox_inches="tight")
    plt.close(fig)

    # ---- Figure 2: Rebased relative wealth (price-basis → cap benchmark) --
    fig, axes = plt.subplots(1, 2, figsize=(13, 5), sharex=True)
    fig.suptitle(
        "Price-Basis Portfolios Rebased to Cap-Weighted Benchmark (Synthetic Data)\n"
        "[DISCLAIMER: synthetic data — not actual CRSP/NYSE data]",
        fontsize=11,
    )
    for ax, univ_label, W_arr, title in [
        (axes[0], "P", W_P, r"Price-wtd portfolios on $U^P$, rebased to $I_\mu^P$"),
        (axes[1], "S", W_S, r"Price-wtd portfolios on $U^S$, rebased to $I_\mu^S$"),
    ]:
        for p_val, col in zip(P_VALUES, COLORS_P):
            key = (p_val, "price", univ_label)
            res = results[key]
            rebased = res["log_rel_wealth"] + W_arr
            ax.plot(trading_dates, rebased.values, lw=1.1, color=col, label=f"$p={p_val}$")
        ax.plot(trading_dates, W_arr.values, lw=1.5, color="grey", ls="--", label=r"$W^M$ (benchmark itself)")
        ax.axhline(0, color="black", lw=0.6, ls=":")
        ax.set_title(title, fontsize=9)
        ax.set_ylabel(r"log(V / $I_\mu$)")
        ax.legend(fontsize=7)
        _set_year_ticks(ax)

    plt.tight_layout()
    fig.savefig(RESULTS_DIR / "exp4_rebased_wealth.png", bbox_inches="tight")
    plt.close(fig)

    # ---- Figure 3: Decomposition verification – selected p values ---------
    sel_p = [0.3, 0.7]   # two values for clear illustration
    fig, axes = plt.subplots(len(sel_p), 2, figsize=(13, 4 * len(sel_p)), sharex=True)
    fig.suptitle(
        "C_p + E_p Decomposition vs Direct Log Relative Wealth (Synthetic Data)\n"
        "[DISCLAIMER: synthetic data — not actual CRSP/NYSE data]",
        fontsize=11,
    )
    for row_idx, p_val in enumerate(sel_p):
        for col_idx, (basis, univ_label, bench_lbl) in enumerate([
            ("price", "P", r"$I_\nu^P$"),
            ("cap",   "S", r"$I_\mu^S$"),
        ]):
            ax = axes[row_idx, col_idx] if len(sel_p) > 1 else axes[col_idx]
            key = (p_val, basis, univ_label)
            res = results[key]
            direct = res["log_rel_wealth"].values
            C_plus_E = res["C_plus_E"].values
            J = res["J_p"].values

            ax.plot(trading_dates, direct,        lw=1.4, color="black",      label=r"Direct $\log(V/I)$")
            ax.plot(trading_dates, C_plus_E,      lw=1.1, color="steelblue",  label=r"$C_p + E_p$", ls="--")
