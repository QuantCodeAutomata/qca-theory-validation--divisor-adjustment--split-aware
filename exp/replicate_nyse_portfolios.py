"""
replicate_nyse_portfolios.py  –  Experiment 4
==============================================
Replication of the NYSE diversity-portfolio study (analogous to Experiment 4
in the accompanying paper) using a *synthetic* equity market.

DISCLAIMER
----------
The CRSP (Center for Research in Security Prices) database is proprietary and
is NOT available in this environment.  All computations below use a synthetic
market generated by :func:`src.synthetic_nyse.generate_synthetic_nyse`, which
is calibrated to approximate NYSE 2002–2021 characteristics but does NOT
replicate specific historical CRSP returns or actual NYSE data.  Results are
structural analogs intended to illustrate SPT portfolio theory in action.

What this script does
---------------------
1. Regenerate the same synthetic NYSE market used in Experiment 3.
2. Rebuild the same quarterly universes U^P and U^S.
3. Rebuild benchmark indices I_nu^P, I_mu^P, I_nu^S, I_mu^S.
4. For each (p, basis, universe) combination (5 × 2 × 2 = 20 portfolios):
   a. Run a daily-rebalanced diversity-p portfolio.
   b. Compute log relative wealth log(V_pi / I) vs own benchmark.
   c. Compute the C_p, E_p, J_p decomposition.
   d. Verify C_p + E_p ≈ log(V_pi / I).
5. Rebase price-basis portfolios to cap-weighted benchmark via the weighting
   effect W^M computed in step 3.
6. Save terminal-value tables to results/exp4_*.csv.
7. Save comparative plots to results/exp4_*.png.
"""

