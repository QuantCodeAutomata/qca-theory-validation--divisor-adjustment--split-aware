def _build_weight_matrices(P, N, m, quarterly_universes, trading_dates, basis):
    P_shifted = P.shift(1)
    all_tickers = sorted({t for u in quarterly_universes.values() for t in u if t in P.columns})
    n_dates = len(trading_dates)
    n_tickers = len(all_tickers)
    ticker_loc = {t: i for i, t in enumerate(all_tickers)}
    date_loc = {d: i for i, d in enumerate(trading_dates)}

    w_end_arr = np.zeros((n_dates, n_tickers), dtype=float)
    w_adj_arr = np.zeros((n_dates, n_tickers), dtype=float)

    rebal_sorted = sorted(quarterly_universes.keys())
    for q_idx, rdate in enumerate(rebal_sorted):
        universe = quarterly_universes[rdate]
        cols = [c for c in universe if c in P.columns]
        if not cols:
            continue
        col_locs = np.array([ticker_loc[c] for c in cols])

        next_rdate = rebal_sorted[q_idx + 1] if q_idx + 1 < len(rebal_sorted) else None
        if next_rdate is not None:
            qmask = (trading_dates >= rdate) & (trading_dates < next_rdate)
        else:
            qmask = trading_dates >= rdate

        qdates = trading_dates[qmask]
        if len(qdates) == 0:
            continue
        q_row_locs = np.array([date_loc[d] for d in qdates])

        # End-of-day weights
        P_q = P.loc[qdates, cols].values.astype(float)
        P_q = np.maximum(P_q, 0.0)
        if basis == "price":
            totals = P_q.sum(axis=1, keepdims=True)
            w_q = np.where(totals > 0, P_q / totals, 0.0)
        else:
            N_q = N.loc[qdates, cols].values.astype(float)
            S_q = P_q * N_q
            totals = S_q.sum(axis=1, keepdims=True)
            w_q = np.where(totals > 0, S_q / totals, 0.0)
        w_end_arr[np.ix_(q_row_locs, col_locs)] = w_q

        # Adjusted start-of-day weights
        P_prev_q = P_shifted.loc[qdates, cols].values.astype(float)
        m_q = m.loc[qdates, cols].values.astype(float)
        with np.errstate(invalid="ignore", divide="ignore"):
            P_dmd_q = P_prev_q / m_q
        P_dmd_q = np.where(np.isfinite(P_dmd_q) & (P_dmd_q > 0), P_dmd_q, 0.0)

        if basis == "price":
            totals = P_dmd_q.sum(axis=1, keepdims=True)
            w_dmd_q = np.where(totals > 0, P_dmd_q / totals, 0.0)
        else:
            N_q = N.loc[qdates, cols].values.astype(float)
            S_dmd_q = P_dmd_q * N_q
            totals = S_dmd_q.sum(axis=1, keepdims=True)
            w_dmd_q = np.where(totals > 0, S_dmd_q / totals, 0.0)
        w_adj_arr[np.ix_(q_row_locs, col_locs)] = w_dmd_q

    w_end = pd.DataFrame(w_end_arr, index=trading_dates, columns=all_tickers)
    w_adj = pd.DataFrame(w_adj_arr, index=trading_dates, columns=all_tickers)
    return w_end, w_adj


def _get_split_dates(m, quarterly_universes, trading_dates):
    """Return trading dates where any active-universe stock had a split."""
    active = _precompute_active_universes(trading_dates, quarterly_universes)
    split_dates = []
    for t, date in enumerate(trading_dates):
        cols = [c for c in active[t] if c in m.columns]
        if cols:
            m_row = m.loc[date, cols].values
            if (m_row != 1.0).any():
                split_dates.append(date)
    return pd.DatetimeIndex(split_dates)


def _get_rebal_dates(quarterly_universes):
    return pd.DatetimeIndex(sorted(quarterly_universes.keys()))


# ---------------------------------------------------------------------------
# Decomposition: C_p + E_p (vectorised where possible)
# ---------------------------------------------------------------------------

def _compute_decomposition(w_end_arr, w_adj_arr, p, trading_dates):
    """Compute C_p and E_p from pre-built weight arrays (numpy).

    Parameters
    ----------
    w_end_arr : np.ndarray, shape (T, d)
    w_adj_arr : np.ndarray, shape (T, d)
    p : float
    trading_dates : DatetimeIndex

    Returns
    -------
    C_p, E_p : pd.Series
    """
    T, d = w_end_arr.shape

    # ---- C_p ----
    # D_p(w) = (sum w_i^p)^{1/p}   (batch over all dates)
    def _batch_Dp(arr):
        clipped = np.clip(arr, 0.0, None)
        row_sums = clipped.sum(axis=1, keepdims=True)
        safe = np.where(row_sums > 0, clipped / row_sums, clipped)
        A = (safe ** p).sum(axis=1)
        return np.where(A > 0, A ** (1.0 / p), 1.0)

    Dp_end = _batch_Dp(w_end_arr)   # shape (T,)
    Dp_adj = _batch_Dp(w_adj_arr)   # shape (T,)

    log_ratio = np.log(Dp_end / Dp_adj)
    log_ratio = np.where(np.isfinite(log_ratio), log_ratio, 0.0)
    C_p_vals = np.cumsum(log_ratio)

    # ---- E_p ----
    # For each date, compute (1/2) delta^T H_Dp(w_adj) delta, then negate & cumsum
    qf_vals = np.zeros(T)
    for t in range(T):
        x = w_adj_arr[t]
        delta = w_end_arr[t] - x
        # Restrict to positive-weight entries
        mask = x > 0
        if mask.sum() < 2:
            continue
        x_m = x[mask]
        d_m = delta[mask]
        A = np.sum(x_m ** p)
        if A <= 0:
            continue
        # Use normalised Hessian H_{D_p} / D_p to avoid numerical overflow
        # for small p with large universes.  The paper formula is:
        #   E_p term = (1/2) delta^T [H_{D_p}(x) / D_p(x)] delta
        # Normalised: H_ii/Dp = (p-1)/A * x_i^{p-2} + (1-p)/A^2 * x_i^{2p-2}
        #             H_ij/Dp = (1-p)/A^2 * x_i^{p-1} * x_j^{p-1}
        term1 = (p - 1.0) / A * np.sum(x_m ** (p - 2.0) * d_m ** 2)
        inner = np.sum(x_m ** (p - 1.0) * d_m)
        term2 = (1.0 - p) / (A ** 2) * inner ** 2
        qf_vals[t] = 0.5 * (term1 + term2)

    E_p_vals = -np.cumsum(qf_vals)

    return (
        pd.Series(C_p_vals, index=trading_dates, name="C_p"),
        pd.Series(E_p_vals, index=trading_dates, name="E_p"),
    )


def _compute_Jp(w_adj_arr, w_end_arr, split_dates, rebal_dates, p, trading_dates, all_tickers):
    """Compute J_p only on split dates (not rebal dates)."""
    pure_split = split_dates.difference(rebal_dates)
    date_loc = {d: i for i, d in enumerate(trading_dates)}
    increments = np.zeros(len(trading_dates))

    for date in pure_split:
        if date not in date_loc:
            continue
        t = date_loc[date]
        x_adj = w_adj_arr[t]
        # Previous end-of-day weights
        if t == 0:
            continue
        x_prev = w_end_arr[t - 1]

        A_adj = np.sum(np.where(x_adj > 0, x_adj ** p, 0.0))
        A_prev = np.sum(np.where(x_prev > 0, x_prev ** p, 0.0))
        if A_adj > 0 and A_prev > 0:
            Dp_adj = A_adj ** (1.0 / p)
            Dp_prev = A_prev ** (1.0 / p)
            ratio = Dp_adj / Dp_prev
            if ratio > 0:
                increments[t] = np.log(ratio)

    J_p_vals = np.cumsum(increments)
    return pd.Series(J_p_vals, index=trading_dates, name="J_p")


