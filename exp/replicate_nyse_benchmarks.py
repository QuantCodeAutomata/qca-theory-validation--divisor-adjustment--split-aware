    _set_year_ticks(ax)

    plt.tight_layout()
    fig.savefig(RESULTS_DIR / "exp3_benchmarks.png", bbox_inches="tight")
    plt.close(fig)

    # ---- Figure 2: Gibbs entropy ----------------------------------------
    fig, axes = plt.subplots(2, 1, figsize=(11, 7), sharex=True)
    fig.suptitle(
        "Gibbs Entropy of Benchmark Weights (Synthetic Data)\n"
        "[DISCLAIMER: synthetic data — not actual CRSP/NYSE data]",
        fontsize=11,
    )

    ax = axes[0]
    ax.plot(trading_dates, H_mu_P.values, lw=1.1, label=r"$H(\mu^P)$ cap-wtd / price-univ", color="steelblue")
    ax.plot(trading_dates, H_mu_S.values, lw=1.1, label=r"$H(\mu^S)$ cap-wtd / cap-univ",   color="navy", ls="--")
    ax.axhline(H_max, color="grey", lw=0.8, ls=":", label=f"$H_{{max}}$ = {H_max:.2f}")
    ax.set_ylabel("Entropy (nats)")
