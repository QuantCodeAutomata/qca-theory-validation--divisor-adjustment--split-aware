    ax = axes[0]
    ax.plot(trading_dates, L_mu_P.values, lw=1.2, label=r"$L_{\mu}^{P}$ cap-wtd / price-univ", color="steelblue")
    ax.plot(trading_dates, L_mu_S.values, lw=1.2, label=r"$L_{\mu}^{S}$ cap-wtd / cap-univ",  color="navy", ls="--")
    ax.plot(trading_dates, L_nu_P.values, lw=1.2, label=r"$L_{\nu}^{P}$ price-wtd / price-univ", color="firebrick")
    ax.plot(trading_dates, L_nu_S.values, lw=1.2, label=r"$L_{\nu}^{S}$ price-wtd / cap-univ",  color="salmon", ls="--")
