"""
replicate_nyse_benchmarks.py  –  Experiment 3
==============================================
Replication of the NYSE benchmark comparison study (analogous to Experiment 3
in the accompanying paper) using a *synthetic* equity market.

DISCLAIMER
----------
The CRSP (Center for Research in Security Prices) database is proprietary and
is NOT available in this environment.  All computations below use a synthetic
market generated by :func:`src.synthetic_nyse.generate_synthetic_nyse`, which
is calibrated to approximate NYSE 2002–2021 characteristics (cross-sectional
price dispersion, market-cap heterogeneity, split frequency) but does NOT
replicate specific historical CRSP returns, constituent lists, or any other
proprietary CRSP data.  Results are intended to illustrate structural
properties of price-based SPT and should be interpreted as evidence from a
structural analog, not as an empirical replication of actual NYSE data.

What this script does
---------------------
1. Generate a 600-stock synthetic market spanning 2002–2021 (5 036 trading days).
2. Reconstitute quarterly universes:
   U^P – top 500 stocks by nominal closing price (price-universe).
   U^S – top 500 stocks by market capitalisation (cap-universe).
3. Build four chain-linked benchmarks (cap and price weighted, for each universe).
4. Compute log levels L_mu^P, L_mu^S, L_nu^P, L_nu^S.
5. Decompose the headline gap D = L_nu^P - L_mu^S into weighting and selection
   effects and verify the accounting identities.
6. Compute Gibbs entropy H(mu^M) and H(nu^M) for all four benchmark variants.
7. Report universe overlap/turnover diagnostics and split statistics.
8. Save all results to results/exp3_*.csv and results/exp3_*.png.
"""

