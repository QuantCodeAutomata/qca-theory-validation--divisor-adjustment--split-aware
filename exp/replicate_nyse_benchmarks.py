    ax.plot(trading_dates, decomp["W_P"].values,  lw=1.0, label=r"$W^P$ (weighting, price univ)", color="darkorange", ls="-")
    ax.plot(trading_dates, decomp["W_S"].values,  lw=1.0, label=r"$W^S$ (weighting, cap univ)",  color="goldenrod",  ls="--")
    ax.plot(trading_dates, decomp["C_mu"].values, lw=1.0, label=r"$C^\mu$ (selection, cap wtd)",  color="seagreen",   ls="-")
    ax.plot(trading_dates, decomp["C_nu"].values, lw=1.0, label=r"$C^\nu$ (selection, price wtd)",color="teal",      ls="--")
    ax.axhline(0, color="grey", lw=0.5)
    ax.set_ylabel("Log-return difference")
    ax.set_xlabel("Date")
    ax.legend(fontsize=8, ncol=2)
