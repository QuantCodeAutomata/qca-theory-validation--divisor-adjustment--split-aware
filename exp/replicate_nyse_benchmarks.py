def main() -> None:
    print("=" * 65)
    print("Experiment 3 – NYSE Benchmark Comparison (Synthetic Data)")
    print("=" * 65)
    print()
    print("DISCLAIMER: CRSP data is NOT available. This experiment uses a")
    print("synthetic market calibrated to NYSE 2002-2021 characteristics.")
    print("Results illustrate structural SPT properties, not historical data.")
    print()

    # ------------------------------------------------------------------
    # 1. Generate synthetic NYSE market
    # ------------------------------------------------------------------
    print("[1/7] Generating synthetic NYSE market (600 stocks, 5 036 days)…")
    P, N, m, trading_dates = generate_synthetic_nyse(
        n_stocks=600,
        n_trading_days=5036,
        seed=42,
        split_prob_annual=0.08,
        reverse_split_prob_annual=0.02,
        sigma_cross=0.20,
        mu_annual=0.08,
        start_date="2002-01-02",
        price_range=(5.0, 500.0),
        cap_range=(1e8, 1e12),
    )
    S = P * N  # market caps
    split_stats = compute_split_statistics(m)
    print(f"    Generated: {len(trading_dates)} trading days, "
          f"{P.shape[1]} stocks, "
          f"dates {trading_dates[0].date()} – {trading_dates[-1].date()}")
    print(f"    Total split events: {(m != 1).values.sum()}")

    # ------------------------------------------------------------------
    # 2. Quarterly universe construction
    # ------------------------------------------------------------------
    print("[2/7] Building quarterly universes U^P (by price) and U^S (by cap)…")
    universes_P, universes_S = build_quarterly_universes(P, S, trading_dates, n=500)
    n_quarters = len(universes_P)
    print(f"    Quarters: {n_quarters}  |  Universe size target: 500")

    diag = compute_universe_diagnostics(universes_P, universes_S)
    print(f"    Mean cross-method overlap (|U^P ∩ U^S|): "
          f"{diag['overlap_PS'].mean():.1f} stocks")
    print(f"    Mean quarterly turnover U^P: {diag['turnover_P'].mean():.1f} stocks")
    print(f"    Mean quarterly turnover U^S: {diag['turnover_S'].mean():.1f} stocks")

    # ------------------------------------------------------------------
    # 3. Build four chain-linked benchmarks
    # ------------------------------------------------------------------
    print("[3/7] Building four chain-linked benchmark indices…")

    I_mu_P, _ = (build_cap_weighted_benchmark(P, N, m, universes_P, trading_dates),
                 None)
    I_mu_P = build_cap_weighted_benchmark(P, N, m, universes_P, trading_dates)
    I_mu_S = build_cap_weighted_benchmark(P, N, m, universes_S, trading_dates)
    I_nu_P, kappa_P = build_price_weighted_benchmark(P, N, m, universes_P, trading_dates)
    I_nu_S, kappa_S = build_price_weighted_benchmark(P, N, m, universes_S, trading_dates)

    print(f"    I_mu^P terminal: {I_mu_P.iloc[-1]:.4f}")
    print(f"    I_mu^S terminal: {I_mu_S.iloc[-1]:.4f}")
    print(f"    I_nu^P terminal: {I_nu_P.iloc[-1]:.4f}")
    print(f"    I_nu^S terminal: {I_nu_S.iloc[-1]:.4f}")

    # Log levels (rebased to 0 at t=0)
    L_mu_P = np.log(I_mu_P)
    L_mu_S = np.log(I_mu_S)
    L_nu_P = np.log(I_nu_P)
    L_nu_S = np.log(I_nu_S)

    # ------------------------------------------------------------------
    # 4. Benchmark gap decomposition
    # ------------------------------------------------------------------
    print("[4/7] Computing benchmark gap decomposition…")
    decomp = compute_benchmark_decomposition(L_mu_P, L_mu_S, L_nu_P, L_nu_S)

    # Verify identities: D should equal W_P + C_mu and W_S + C_nu
    err1 = (decomp["D"] - decomp["check_WP_Cmu"]).abs().max()
    err2 = (decomp["D"] - decomp["check_WS_Cnu"]).abs().max()
    print(f"    Headline gap D(T)  = {decomp['D'].iloc[-1]:.4f}")
    print(f"    W^P (weighting, price univ): {decomp['W_P'].iloc[-1]:.4f}")
    print(f"    W^S (weighting, cap univ):   {decomp['W_S'].iloc[-1]:.4f}")
    print(f"    C^mu (selection, cap wtd):   {decomp['C_mu'].iloc[-1]:.4f}")
    print(f"    C^nu (selection, price wtd): {decomp['C_nu'].iloc[-1]:.4f}")
    print(f"    Identity check |D - (W^P + C^mu)|_inf: {err1:.2e}")
    print(f"    Identity check |D - (W^S + C^nu)|_inf: {err2:.2e}")

    # ------------------------------------------------------------------
    # 5. Gibbs entropy
    # ------------------------------------------------------------------
    print("[5/7] Computing Gibbs entropy for all four benchmark combinations…")
    H_mu_P = _compute_entropy_from_matrices(universes_P, trading_dates, P, N, "cap")
    H_mu_S = _compute_entropy_from_matrices(universes_S, trading_dates, P, N, "cap")
    H_nu_P = _compute_entropy_from_matrices(universes_P, trading_dates, P, N, "price")
    H_nu_S = _compute_entropy_from_matrices(universes_S, trading_dates, P, N, "price")

    H_max = np.log(500)  # maximum entropy for 500 stocks (equal weights)
    print(f"    H_max (500 stocks) = {H_max:.4f}")
    print(f"    Mean H(mu^P) = {H_mu_P.mean():.4f}  ({H_mu_P.mean()/H_max:.1%} of max)")
    print(f"    Mean H(mu^S) = {H_mu_S.mean():.4f}  ({H_mu_S.mean()/H_max:.1%} of max)")
    print(f"    Mean H(nu^P) = {H_nu_P.mean():.4f}  ({H_nu_P.mean()/H_max:.1%} of max)")
    print(f"    Mean H(nu^S) = {H_nu_S.mean():.4f}  ({H_nu_S.mean()/H_max:.1%} of max)")

