"""
generators.py
=============
Generating functions and portfolio construction routines for additive and
multiplicative functional generation in price-based Stochastic Portfolio Theory
(SPT).

Mathematical background
-----------------------
Additive generation (Section 3 of the companion paper):
  A differentiable function G: Delta^d → R generates an additive portfolio phi
  via phi_i(t) = (partial_i G)(nu_adj(t)), where nu_adj(t) is the adjusted
  start-of-day price-weight vector.

  The additive master identity is:
      V^phi(t) ≈ G^c(nu(t)) + Gamma^{G,c}(t)

  where G^c is the jump-corrected generator and Gamma^{G,c} the continuous
  gamma (first-order Taylor gain from market moves).

Multiplicative generation:
  A positive function G generates a multiplicative portfolio phi via
  phi_i(t) = (partial_i G / G)(nu(t)) scaled to the simplex.

Key generating functions implemented here:
  - Gibbs (Shannon) entropy:  H(x) = -sum_i x_i log x_i
  - Diversity function:        D_p(x) = (sum_i x_i^p)^{1/p}   (0 < p <= 1)

References: Fernholz (2002) *Stochastic Portfolio Theory*, Springer.
"""

import numpy as np
from typing import Callable, Optional, Tuple

# ---------------------------------------------------------------------------
# Gibbs (Shannon) entropy  H(x) = -sum_i x_i log x_i
# ---------------------------------------------------------------------------


def gibbs_entropy(x: np.ndarray, eps: float = 1e-15) -> float:
    """Gibbs entropy H(x) = -sum_i x_i log(x_i).

    The convention 0 * log(0) = 0 (information-theoretic) is enforced by
    clipping x_i away from 0 before taking the logarithm.

    In price-based SPT, H(nu(t)) measures the *spread* of the price-weight
    distribution: maximum entropy (= log d) when all prices are equal, minimum
    (= 0) when one asset dominates.  Generating a portfolio with H produces
    a strategy that benefits from mean-reversion of price weights.

    Parameters
    ----------
    x : np.ndarray, shape (d,)
        Weight vector; should sum to 1 and have non-negative entries.
    eps : float
        Floor applied to x_i before log to avoid log(0).  Default 1e-15.

    Returns
    -------
    float
        H(x) >= 0.
    """
    x = np.asarray(x, dtype=float)
    x_safe = np.clip(x, eps, None)  # replace near-zero entries for log stability
    return float(-np.sum(x_safe * np.log(x_safe)))


def gibbs_entropy_gradient(x: np.ndarray, eps: float = 1e-15) -> np.ndarray:
    """Gradient of the Gibbs entropy: dH/dx_i = -(1 + log x_i).

    At a probability vector x in the interior of the simplex, the gradient is:
        grad H(x)_i = -(1 + log x_i)

    This is the *unconstrained* gradient; the tangent-plane projection onto
    the simplex subtracts the mean, but for portfolio construction purposes
    the unconstrained version is used directly as a price-weight allocation.

    Parameters
    ----------
    x : np.ndarray, shape (d,)
        Weight vector (all entries > 0 for the gradient to be finite).
    eps : float
        Floor for x_i to avoid log(0).

    Returns
    -------
    np.ndarray, shape (d,)
        Gradient vector.
    """
    x = np.asarray(x, dtype=float)
    x_safe = np.clip(x, eps, None)
    return -(1.0 + np.log(x_safe))


def gibbs_entropy_hessian(x: np.ndarray, eps: float = 1e-15) -> np.ndarray:
    """Hessian of the Gibbs entropy.

    The exact Hessian is diagonal:
        d^2 H / dx_i^2  = -1 / x_i    (diagonal entries)
        d^2 H / dx_i dx_j = 0          (off-diagonal; H is separable)

    The negative-definite Hessian confirms that H is concave, which is the
    key property ensuring the entropy-generated portfolio is long-run growth
    optimal in a symmetric market.

    Parameters
    ----------
    x : np.ndarray, shape (d,)
        Weight vector (all entries > 0).
    eps : float
        Floor for x_i to avoid division by zero.

    Returns
    -------
    np.ndarray, shape (d, d)
        Hessian matrix (diagonal with entries -1/x_i).
    """
    x = np.asarray(x, dtype=float)
    x_safe = np.clip(x, eps, None)
    d = len(x)
    # Hessian is diagonal: H_{ii} = -1/x_i
    return np.diag(-1.0 / x_safe)


# ---------------------------------------------------------------------------
# Diversity function  D_p(x) = (sum_i x_i^p)^{1/p}
# ---------------------------------------------------------------------------


def diversity_function(w: np.ndarray, p: float) -> float:
    """Diversity function D_p(w) = (sum_i w_i^p)^{1/p}.

    For p in (0, 1), Jensen's inequality gives D_p(w) < 1 whenever weights
    are not concentrated on a single asset, so a multiplicative portfolio
    generated by D_p earns a positive excess-growth premium.

    D_p → 1 as p → 0 (Shan­non entropy sense) and D_1(w) = 1 always.

    Parameters
    ----------
    w : np.ndarray, shape (d,)
        Non-negative weight vector (all entries strictly positive for gradient
        and Hessian to be defined).
    p : float
        Diversity parameter, typically in (0, 1].

    Returns
    -------
    float
        D_p(w).
    """
    w = np.asarray(w, dtype=float)
    A = np.sum(w ** p)   # p-th power sum
    return float(A ** (1.0 / p))


def diversity_gradient(w: np.ndarray, p: float) -> np.ndarray:
    """Gradient of D_p(w) with respect to w.

    By the chain rule applied to D_p = A^{1/p} where A = sum_k w_k^p:

        dD_p / dw_i = A^{1/p - 1} * w_i^{p-1}

    Note that for p < 1 the gradient diverges as any w_i → 0, reflecting
    the portfolio's preference for diversification.

    Parameters
    ----------
    w : np.ndarray, shape (d,)
        Weight vector (all entries > 0).
    p : float
        Diversity parameter.

    Returns
    -------
    np.ndarray, shape (d,)
        Gradient evaluated at w.
    """
    w = np.asarray(w, dtype=float)
    A = np.sum(w ** p)
    return A ** (1.0 / p - 1.0) * w ** (p - 1.0)


def diversity_hessian(w: np.ndarray, p: float) -> np.ndarray:
    """Full Hessian matrix of D_p(w).

    Second derivatives (derived from repeated application of the chain rule):

        H_{ii} = (p-1)*A^{1/p-1}*w_i^{p-2}  +  (1-p)*A^{1/p-2}*w_i^{2p-2}
        H_{ij} = (1-p)*A^{1/p-2}*w_i^{p-1}*w_j^{p-1}    (i ≠ j)

    where A = sum_k w_k^p.  The off-diagonal part has a rank-1 structure, so
    the Hessian can be written as H = c1 * diag(w^{p-2}) + c2 * (w^{p-1})(w^{p-1})^T.

    Parameters
    ----------
    w : np.ndarray, shape (d,)
        Weight vector (all entries > 0).
    p : float
        Diversity parameter.

    Returns
    -------
    np.ndarray, shape (d, d)
        Hessian matrix.
    """
    w = np.asarray(w, dtype=float)
    A = np.sum(w ** p)

    c1 = (p - 1.0) * A ** (1.0 / p - 1.0)    # coefficient of diagonal part
    c2 = (1.0 - p) * A ** (1.0 / p - 2.0)    # coefficient of rank-1 outer product

    v = w ** (p - 1.0)
    H = c2 * np.outer(v, v)                   # rank-1 off-diagonal contribution
    np.fill_diagonal(H, H.diagonal() + c1 * w ** (p - 2.0))  # diagonal correction
    return H


def log_diversity_hessian(w: np.ndarray, p: float) -> np.ndarray:
    """Full Hessian of log D_p(w).

    Derived from H(log f) = H(f)/f - (grad f)(grad f)^T / f^2:

        H_{ij}(log D_p) = H_{ij}(D_p) / D_p  -  g_i * g_j / D_p^2

    Useful for computing the quadratic excess-growth rate of D_p-generated
    multiplicative portfolios.

    Parameters
    ----------
    w : np.ndarray, shape (d,)
    p : float

    Returns
    -------
    np.ndarray, shape (d, d)
    """
    w = np.asarray(w, dtype=float)
    Dp = diversity_function(w, p)
    H = diversity_hessian(w, p) / Dp
    g = diversity_gradient(w, p)
    H -= np.outer(g, g) / (Dp ** 2)
    return H


# ---------------------------------------------------------------------------
# Balance defect
# ---------------------------------------------------------------------------


def balance_defect(G: Callable, grad_G: Callable, x: np.ndarray) -> float:
    """Balance defect b_G(x) = grad_G(x) · x - G(x).

    In SPT the balance defect appears in the master formula as the drift
    adjustment that links the portfolio allocation to the generator value.

    For Gibbs entropy H:
        grad H(x) · x = -sum_i x_i (1 + log x_i) = -(1 + H(x)) ... wait:
        = -sum_i x_i - sum_i x_i log x_i = -1 + H(x)  ... so
        b_H(x) = (H(x) - 1) - H(x) = -1   (constant for any probability vector)

    For diversity D_p:
        b_{D_p}(x) = (sum_i x_i * x_i^{p-1} * A^{1/p-1}) - A^{1/p}
                   = A^{1/p-1} * A - A^{1/p} = A^{1/p} - A^{1/p} = 0
        when sum x_i = 1 and A = sum x_i^p.  Wait:
        grad D_p . x = A^{1/p-1} * sum_i x_i^p = A^{1/p-1} * A = A^{1/p} = D_p(x)
        b_{D_p}(x) = D_p(x) - D_p(x) = 0.

    Parameters
    ----------
    G : callable
        Scalar-valued generator G(x).
    grad_G : callable
        Gradient of G; returns array of shape (d,).
    x : np.ndarray, shape (d,)
        Evaluation point.

    Returns
    -------
    float
        Balance defect b_G(x).
    """
    x = np.asarray(x, dtype=float)
    return float(np.dot(grad_G(x), x) - G(x))


# ---------------------------------------------------------------------------
# Jump-corrected generator  G^c
# ---------------------------------------------------------------------------


def compute_jump_corrected_state_additive(
    G: Callable,
    nu_path: np.ndarray,
    is_split: np.ndarray,
) -> np.ndarray:
    """Jump-corrected state G^c(nu(t)) for additive generation.

    In the presence of stock splits, the raw generator G(nu(t)) has
    discontinuities at split times because nu(t) itself jumps.  The
    corrected version removes these split-induced jumps so that G^c is
    continuous along the path:

        G^c(nu(t)) = G(nu(t)) - sum_{0 < s <= t, split at s}
                        [G(nu(s)) - G(nu(s-))]

    where nu(s-) = nu_path[s-1] (end of previous day, pre-split weight) and
    nu(s) = nu_path[s] (end of current split day, post-split + post-market).

    On non-split days, G^c(nu(t)) evolves continuously with the market.
    At split day s, the cumulative correction Gamma^{G,d} absorbs the total
    change in G, so G^c remains at the level it had just before the split.

    Parameters
    ----------
    G : callable
        Generating function G: R^d → R.
    nu_path : np.ndarray, shape (T+1, d)
        End-of-day price-weight path including split and market effects.
    is_split : np.ndarray, shape (T+1, d), dtype bool
        is_split[t, i] = True if asset i had a split on day t.

    Returns
    -------
    np.ndarray, shape (T+1,)
        G^c(nu(t)) for t = 0, ..., T.
    """
    nu_path  = np.asarray(nu_path,  dtype=float)
    is_split = np.asarray(is_split, dtype=bool)
    T_plus_1 = nu_path.shape[0]

    # Evaluate G at each time step
    G_nu = np.array([G(nu_path[t]) for t in range(T_plus_1)])

    # Accumulate jump corrections: at each split day s, remove
    # [G(nu(s)) - G(nu(s-))] = G_nu[s] - G_nu[s-1] from G^c.
    jump_correction = np.zeros(T_plus_1)
    for t in range(1, T_plus_1):
        # Any split event on day t (across any asset) triggers a correction
        if is_split[t].any():
            delta_G = G_nu[t] - G_nu[t - 1]     # total change in G at split day
            jump_correction[t] = delta_G
    cumulative_correction = np.cumsum(jump_correction)

    # G^c(nu(t)) = G(nu(t)) - accumulated split jumps up to t
    return G_nu - cumulative_correction


# ---------------------------------------------------------------------------
# Gamma processes  Gamma^{G,c} and Gamma^{G,d}
# ---------------------------------------------------------------------------


def compute_gamma_continuous(
    G: Callable,
    grad_G: Callable,
    nu_path: np.ndarray,
    nu_adj: np.ndarray,
    is_split: np.ndarray,
) -> np.ndarray:
    """Continuous part of the gamma process Gamma^{G,c}(t).

    The continuous gamma accumulates the first-order Taylor gains from
    *market moves* only (split-induced jumps are excluded):

        Gamma^{G,c}(t) = sum_{s=1}^{t} grad_G(nu_adj(s)) · (nu(s) - nu_adj(s))

    Here:
      - nu_adj(s) is the adjusted start-of-day price weight (post-split,
        pre-market-move).  On non-split days nu_adj(s) = nu_path(s-1).
      - nu(s) - nu_adj(s) is the *market-move increment* on day s (the
        change from the split-adjusted open to the close).

    The term grad_G(nu_adj(s)) · (nu(s) - nu_adj(s)) is the linear
    (first-order) portfolio return on day s under the G-generated strategy.

    Parameters
    ----------
    G : callable
        Not used in this function but included for API consistency.
    grad_G : callable
        Gradient of G; returns array of shape (d,).
    nu_path : np.ndarray, shape (T+1, d)
        End-of-day price weights.
    nu_adj : np.ndarray, shape (T+1, d)
        Adjusted start-of-day price weights (P_diamond / Sigma_diamond).
    is_split : np.ndarray, shape (T+1, d), dtype bool
        Split indicator (not used here but kept for interface symmetry).

    Returns
    -------
    np.ndarray, shape (T+1,)
        Gamma^{G,c}(t) for t = 0, ..., T, with Gamma^{G,c}(0) = 0.
    """
    nu_path  = np.asarray(nu_path,  dtype=float)
    nu_adj   = np.asarray(nu_adj,   dtype=float)
    T_plus_1 = nu_path.shape[0]

    gamma_c = np.zeros(T_plus_1)
    for t in range(1, T_plus_1):
        # grad_G evaluated at the *start-of-day* (split-adjusted) weight
        g = grad_G(nu_adj[t])
        # Market-move increment: from split-adjusted open to close
        d_nu_market = nu_path[t] - nu_adj[t]
        gamma_c[t] = np.dot(g, d_nu_market)

    # Return cumulative sum so that Gamma^{G,c}(t) = sum_{s=1}^{t} increments
    gamma_c_cumul = np.cumsum(gamma_c)
    gamma_c_cumul[0] = 0.0   # redundant because gamma_c[0]=0, but explicit
    return gamma_c_cumul


def compute_gamma_jump(
    G: Callable,
    nu_path: np.ndarray,
    is_split: np.ndarray,
) -> np.ndarray:
    """Jump part of the gamma process Gamma^{G,d}(t).

    At each split time s, the total change in G along the path is:

        Gamma^{G,d}(t) = sum_{0 < s <= t, split at s}
                             [G(nu(s)) - G(nu(s-))]

    where nu(s-) = nu_path[s-1] and nu(s) = nu_path[s].

    Note that this captures the TOTAL change in G on split days (market move
    AND split-induced re-weighting), which is exactly the jump correction
    removed by G^c.  So by construction:

        G^c(nu(t)) + Gamma^{G,d}(t) = G(nu(t))   for all t.

    Parameters
    ----------
    G : callable
    nu_path : np.ndarray, shape (T+1, d)
    is_split : np.ndarray, shape (T+1, d), dtype bool

    Returns
    -------
    np.ndarray, shape (T+1,)
        Gamma^{G,d}(t), with Gamma^{G,d}(0) = 0.
    """
    nu_path  = np.asarray(nu_path,  dtype=float)
    is_split = np.asarray(is_split, dtype=bool)
    T_plus_1 = nu_path.shape[0]

    G_nu = np.array([G(nu_path[t]) for t in range(T_plus_1)])

    gamma_d = np.zeros(T_plus_1)
    for t in range(1, T_plus_1):
        if is_split[t].any():
            gamma_d[t] = G_nu[t] - G_nu[t - 1]   # total G-change at split day

    return np.cumsum(gamma_d)


# ---------------------------------------------------------------------------
# Generated portfolio allocation and wealth
# ---------------------------------------------------------------------------


def compute_generated_strategy_additive(
    grad_G: Callable,
    nu_adj: np.ndarray,
    Sigma_tilde: np.ndarray,
) -> np.ndarray:
    """Additive generated portfolio allocation phi(t).

    The G-generated additive portfolio allocates in proportion to the
    gradient of G evaluated at the *adjusted start-of-day* price weights:

        phi_i(t) = (partial_i G)(nu_adj(t))

    This is expressed as a fraction of the *price-weighted basis* (not a
    fraction of total wealth), consistent with the additive wealth formula.

    The Sigma_tilde argument is retained for API symmetry and potential
    normalisation in extended formulations but is not used in the basic
    additive case.

    Parameters
    ----------
    grad_G : callable
        Gradient of G; returns array of shape (d,).
    nu_adj : np.ndarray, shape (T+1, d)
        Adjusted start-of-day price weights.
    Sigma_tilde : np.ndarray, shape (T+1,)
        Divisor-adjusted total price (unused in base formula; kept for API).

    Returns
    -------
    np.ndarray, shape (T+1, d)
        phi[t] = grad_G(nu_adj[t]) for each time step t.
    """
    nu_adj    = np.asarray(nu_adj,    dtype=float)
    T_plus_1, d = nu_adj.shape
    phi = np.zeros((T_plus_1, d))
    for t in range(T_plus_1):
        phi[t] = grad_G(nu_adj[t])   # allocation vector at time t
    return phi


def compute_additive_wealth(
    phi: np.ndarray,
    nu_path: np.ndarray,
    nu_adj: np.ndarray,
    V0: float = 1.0,
) -> np.ndarray:
    """Wealth of the additive generated strategy.

    In the price-based SPT framework, the wealth of the phi-portfolio is:

        V^phi(t) = V^phi(0) + sum_{s=1}^{t} phi(s-1) · d_nu(s)

    where d_nu(s) = nu(s) - nu_adj(s) is the *market-move increment* on day s
    (the change from the split-adjusted open to the close, excluding any
    split-induced jump in nu).

    phi(s-1) = phi[s-1] = grad_G(nu_adj(s-1)) is the portfolio held during
    period [s-1, s], determined at the end of the previous day.

    On non-split days nu_adj(s) = nu_path(s-1), so d_nu(s) = nu_path(s) -
    nu_path(s-1) is the ordinary price-weight increment.  On split days
    d_nu(s) removes the mechanical split jump, keeping only the economic
    return component.

    Parameters
    ----------
    phi : np.ndarray, shape (T+1, d)
        Portfolio allocations phi[t] = grad_G(nu_adj[t]).
    nu_path : np.ndarray, shape (T+1, d)
        End-of-day price weights.
    nu_adj : np.ndarray, shape (T+1, d)
        Adjusted start-of-day price weights.
    V0 : float
        Initial portfolio wealth (default 1.0).

    Returns
    -------
    np.ndarray, shape (T+1,)
        Wealth series V^phi(t) for t = 0, ..., T.
    """
    phi      = np.asarray(phi,      dtype=float)
    nu_path  = np.asarray(nu_path,  dtype=float)
    nu_adj   = np.asarray(nu_adj,   dtype=float)
    T_plus_1 = nu_path.shape[0]

    wealth = np.empty(T_plus_1)
    wealth[0] = V0

    for t in range(1, T_plus_1):
        # Portfolio set at end of day t-1 (phi[t-1] = grad_G(nu_adj[t-1]))
        phi_prev = phi[t - 1]
        # Market-move increment on day t: nu_path - nu_adj removes split jumps
        d_nu = nu_path[t] - nu_adj[t]
        wealth[t] = wealth[t - 1] + np.dot(phi_prev, d_nu)

    return wealth
